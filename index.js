function searchMovie(){
    const inputField = document.getElementById("search");
    let name = inputField.value;
    name = name.trimStart();
    name = name.replace(/\s+/g, ' ').trim();
    name = name.replace(/\s+/g, '%20');
    console.log(name);
    window.location.href = `index.html?query=${name}`;
}

document.addEventListener("DOMContentLoaded",() => {
    const params = new URLSearchParams(document.location.search);
    const id = params.get('movieID');
    let name = params.get('query');
  
    if(id){
        loadMoviePage(id);
    }
    else if(name){
        
        loadSearchResults(name);
    }
    else{
        loadHomePage();
    }
})

function createSection(){
    const header = document.querySelector('#headers');
    const br = document.createElement('br');
    const section = document.createElement('section');
    section.classList.add('movie-tiles-field');
    header.insertAdjacentElement('afterend',section);
    header.insertAdjacentElement('afterend',br);
    return section;
}

function addMovieCard(movie){
    const movieCard = document.createElement('div');
    movieCard.classList.add('movie-card');
    movieCard.style.cursor='pointer';
    movieCard.addEventListener('click', function(){
        window.location.href=`index.html?movieID=${movie.imdbID}`;
    })
    movieCard.innerHTML=`<img class="poster" src="${movie.Poster}">
            <div class="movie-details">
                <h2>${movie.Title}</h2>
                <p>${movie.Year}</p>
                <p class='card-plot'>${movie.Plot}</p>
            </div>`;
    return movieCard;
}

